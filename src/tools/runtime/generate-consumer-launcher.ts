const CONSUMER_LAUNCHER_FILES = {
  windows: {
    start: 'consumer-start.bat',
    stop: 'consumer-stop.bat',
  },
  linux: {
    start: 'consumer-start.sh',
    stop: 'consumer-stop.sh',
  },
} as const;

// Files written by 'restforge-consumer-deploy' into its output folder
// (cli/consumer-deploy.js:651-658). Used for the pre-flight existence check that
// keeps the CLI away from its interactive overwrite prompt.
const DEPLOY_FILES = ['ecosystem.config.js', 'consumer-manager.sh'] as const;

// Default control-API port of 'restforge-consumer' when --port is omitted
// (cli/consumer.js parseArgs default). The stop script needs a concrete port.
const DEFAULT_CONTROL_PORT = 3001;

const DEFAULT_DEPLOY_DIR = 'deploy';

